"""Generate docs/STAGE_2R_DECISION.md.

Rule 6: reader-facing numbers come from computed artifacts. The decisions are
judgements and are rendered from `replay/stage2r_gate.py` beside the evidence
they rest on.

    .venv/bin/python -m replay.stage2r_gate_report
"""
from __future__ import annotations

import pandas as pd

from models.common import assumptions, study
from replay import stage2r as X
from replay import stage2r_gate as G


def _artifacts() -> dict:
    a = {
        "claims": G.claim_audit(),
        "comp": G.competition_composition(),
        "brands": G.brand_resolution_at_hubs(),
        "shareval": G.share_validation_by_structure(),
        "ranking": G.ranking_exposure(),
        "capfeas": G.ceiling_feasibility(),
        "res": G.resolution_facts(),
        "gates": pd.DataFrame(G.W2_GATES),
        "defects": pd.DataFrame(G.DEFECT_DECISIONS),
    }
    a.update(G.structural_regime())
    G.OUT.mkdir(parents=True, exist_ok=True)
    for n in ("claims", "comp", "brands", "shareval", "ranking", "gates",
              "defects"):
        a[n].to_parquet(G.OUT / f"gate_{n}.parquet", index=False)
    return a


def main() -> str:
    a = _artifacts()
    f = a["freq"]
    res = a["res"]
    gates = a["gates"]
    verdict, reasons = G.gate_verdict(res, gates)
    lo = f["lo"]
    floor = f["lf_floor"]
    seats = int(study(X.STUDY)["fleet"]["seats"])
    menu = study(X.STUDY)["candidates"]["target_frequency_weekly"]

    L = []
    A = L.append
    A("# Stage 2R.5 and the Stage 2R decision gate")
    A("")
    A("**Generated by `replay/stage2r_gate_report.py`. Do not hand-edit.**")
    A("")
    A("A decision stage. Nothing was fitted, calibrated, ingested or repaired; "
      "no model default, assumption, threshold or output changed; D1, D2 and "
      "D3 are still in place exactly as V2 froze them. Stage 2R.0 through "
      "2R.4 are complete through commit `0f98010`.")
    A("")
    A(f"> # Gate verdict: {verdict}")
    A("")
    for r in reasons:
        A(f"> - {r}")
    A("")
    A("**This is not a finding that the model does not work, and it is not a "
      "proof of equivalence with a demand ranking.** Section 4 states the "
      "claim the evidence supports.")
    A("")
    A("---")
    A("")

    # ================================================ 1. the claim boundary
    A("## 1. The product claim")
    A("")
    A("Two products are hiding in the code, and only one of them is built.")
    A("")
    A("| | claim | what it asserts |")
    A("|---|---|---|")
    A("| **A** | fixed-gauge route screening | given the configured gauge and "
      "an allowed schedule menu, is a candidate route economically "
      "supportable, and how do the supportable ones compare |")
    A("| **B** | fleet and frequency right-sizing | what aircraft and "
      "frequency should an airline use in this market |")
    A("")
    A("### What the implementation supports")
    A("")
    A(f"The WestJet study config lists **one gauge** ({seats} seats) and a "
      f"schedule menu of **{', '.join(f'{m}x' for m in menu)} weekly**, with "
      f"the comment that the project will not invent a regional-gauge "
      f"transborder aircraft. Against that menu, 2R.3 measured:")
    A("")
    A("| quantity | value |")
    A("|---|---|")
    A(f"| decision rows | {f['n']} |")
    A(f"| median load factor at {lo}x on the study gauge | "
      f"**{f['median_lf_lo']:.3f}** |")
    A(f"| feasibility floor | {floor:.2f} |")
    A(f"| rows clearing the floor at {lo}x | {f['rows_lf_lo_above_floor']} |")
    A(f"| rows with positive annual contribution at {lo}x | "
      f"{f['rows_ac_lo_positive']} |")
    A(f"| rows where no option clears the floor | "
      f"**{f['paths'].get('fallback: no option clears the load-factor floor', 0)}** |")
    A(f"| rows selecting {lo}x | {f['chose_lo']} |")
    A("")
    A("**Claim B is not supported.** A selector whose menu contains one gauge "
      "and whose smallest schedule already exceeds the capacity the modelled "
      "demand can fill is not choosing an aircraft or a frequency. On "
      f"{f['paths'].get('fallback: no option clears the load-factor floor', 0)} "
      f"of {f['n']} rows it never reaches a comparison, and the branch it "
      "takes instead returns the highest load factor, which is arithmetically "
      "the lowest frequency. 2R.1's control transition confirms the "
      "consequence: ranking by margin at the minimum option and at the chosen "
      "option are the same ordering, Spearman exactly 1.000 at every date.")
    A("")
    A("**Claim A is supported, and most routes failing is a legitimate "
      "result under it.** A screen that says a thin transborder market cannot "
      "support a 737 at three weekly frequencies is answering the question it "
      "was asked. The defect is not the answer; it is the label on the "
      "component that produces it.")
    A("")
    A("**Claim B is not rescued by expansion.** Supporting it would need "
      "smaller gauges the studied carriers do not fly on these routes, "
      "schedules below a real operation, and a fleet-assignment layer. All "
      "three are outside the roadmap's finish line, and the roadmap already "
      "declined to add carriers merely to raise N. Narrowing the claim is the "
      "cheaper and more honest move.")
    A("")
    A("### Decision")
    A("")
    A("> **The product is CLAIM A, fixed-gauge route screening.** "
      "**RETIRE / DE-SCOPE RIGHT-SIZING** as a validated model output.")
    A("")
    A("### The terminology that should replace it")
    A("")
    A("Not applied here. Recorded so the correction is mechanical when it is "
      "made.")
    A("")
    A("| current wording | replacement |")
    A("|---|---|")
    A("| right-sizing, right-sized | fixed-gauge schedule evaluation |")
    A("| picks the frequency and gauge that maximize annual contribution | "
      "evaluates a fixed schedule menu on the study gauge and reports the "
      "best feasible option, or that none is feasible |")
    A("| best schedule | evaluated schedule |")
    A("| `chosen_freq_wk` in reader-facing text | evaluated frequency |")
    A("| optimization, optimizer | screening, evaluation |")
    A("")
    A("The column name in the artifacts may stay `chosen_freq_wk`; what must "
      "change is every sentence that describes it as an optimisation result, "
      "and every place that reports a frequency without saying that the "
      "market had no feasible option.")
    A("")
    A("### Audit: where the claim is currently made")
    A("")
    A("Recomputed from the working tree at generation time, so this table "
      "empties itself when the wording is corrected.")
    A("")
    cl = a["claims"]
    A(f"**{len(cl)} lines across {cl['file'].nunique()} reader-facing "
      "surfaces.**")
    A("")
    A("| file | line | text |")
    A("|---|---|---|")
    for _, r in cl.iterrows():
        A(f"| `{r['file']}` | {r['line']} | {r['text'].replace('|', ' ')} |")
    A("")
    A("`docs/LIMITATIONS.md` already scopes the component correctly at item "
      "11; the other surfaces do not.")
    A("")
    A("---")
    A("")

    # ================================================ 2. necessity gates
    A("## 2. Stage 2R.5: necessity gates")
    A("")
    A("Every old Milestone B task, against all Stage 2R evidence. No task is "
      "carried forward because it appeared in the earlier plan.")
    A("")
    A("| task | classification |")
    A("|---|---|")
    for _, r in gates.iterrows():
        A(f"| **{r['task']}** {r['name']} | **{r['classification']}** |")
    A("")
    for _, r in gates.iterrows():
        A(f"### {r['task']}: {r['name']} - {r['classification']}")
        A("")
        A(f"- **mechanism it would improve**: {r['mechanism']}")
        A(f"- **does that mechanism currently matter**: {r['matters']}")
        A(f"- **could the replay validate the improvement**: {r['validatable']}")
        A(f"- **cost**: {r['cost']}")
        A(f"- **required for a defensible portfolio project**: {r['portfolio']}")
        A(f"- **recommendation**: {r['recommendation']}")
        A("")

    A("### Evidence for W2.2 and W2.3")
    A("")
    A("These two share a layer, and the measurements separate them cleanly.")
    A("")
    A("**What the competitive set is made of.** Preference is the same "
      "QSI-lite quantity `comp_pref_sum` is built from.")
    A("")
    A("| study | itineraries | nonstop | one-stop | one-stop share of "
      "competitor preference | itineraries on an unresolved certificate | "
      "their share of preference |")
    A("|---|---|---|---|---|---|---|")
    for _, r in a["comp"].iterrows():
        A(f"| {r['study_id']} | {r['itineraries']} | {r['nonstop']} | "
          f"{r['onestop']} | **{r['onestop_pref_share']:.1%}** | "
          f"{r['unresolved_brand_itineraries']} | "
          f"{r['unresolved_brand_pref_share']:.1%} |")
    A("")
    A("**Brand resolution where the studies consume it.**")
    A("")
    A("| study | hub | hub-origin departures | flown by a regional operator | "
      "unresolved | unresolved share |")
    A("|---|---|---|---|---|---|")
    for _, r in a["brands"].iterrows():
        A(f"| {r['study_id']} | {r['hub']} | {r['hub_departures']:,.0f} | "
          f"{r['regional_departures']:,.0f} | {r['unresolved_departures']:,.0f} "
          f"| **{r['unresolved_share']:.2%}** |")
    A("")
    A("W2.2 is settled by that table. The brand map already resolves more "
      "than 99.8% of hub-origin flying at all three hubs, and the itineraries "
      "that do carry an unresolved certificate contribute at most "
      f"{a['comp']['unresolved_brand_pref_share'].max():.1%} of competitor "
      "preference. The roadmap's D7 figure counts unmapped triples in the raw "
      "segment universe, which is a different and much larger population than "
      "the flying a candidate's competitive set actually consumes.")
    A("")
    A("**Where the share model has and has not been checked.** "
      "`models/share_validation.py` scores incumbents with the same QSI-lite "
      "the proposals use and compares against observed DB1B ticketing shares.")
    A("")
    sv = a["shareval"]
    A("| nonstop carriers in the market | markets | rows | MAE, share points "
      "| passenger-weighted MAE |")
    A("|---|---|---|---|---|")
    for _, r in sv.iterrows():
        A(f"| {r['n_nonstop_carriers']:.0f} | {r['markets']:.0f} | "
          f"{r['rows']:.0f} | {r['mae_share_points']:.1f} | "
          f"{r['pax_weighted_mae']:.1f} |")
    A("")
    zero = sv[sv["n_nonstop_carriers"] == 0]
    tot_m = sv["markets"].sum()
    A(f"**This is why W2.3 is the one required task.** The check covers "
      f"{tot_m:.0f} markets, of which "
      f"{zero['markets'].iloc[0]:.0f} have no nonstop carrier. The WestJet "
      "study lives almost entirely in that stratum: 85 of 88 candidates have "
      "no nonstop incumbent, and one-stop reconstruction carries "
      f"{a['comp'][a['comp'].study_id == X.STUDY]['onestop_pref_share'].iloc[0]:.0%}"
      " of competitor preference. The layer that does most of the "
      "differentiating is validated in a regime the flagship study barely "
      "occupies. Closing that needs no new source: it is a stratum extension "
      "of a check that already exists.")
    A("")
    A("---")
    A("")

    # ================================================ 3. defect decisions
    A("## 3. Final treatment of D1, D2, D3A and D3B")
    A("")
    A("None is implemented here.")
    A("")
    A("| defect | decision |")
    A("|---|---|")
    for _, r in a["defects"].iterrows():
        A(f"| **{r['defect']}** {r['name']} | **{r['decision']}** |")
    A("")
    for _, r in a["defects"].iterrows():
        A(f"### {r['defect']}: {r['name']} - {r['decision']}")
        A("")
        A(f"**Why.** {r['why']}")
        A("")
        A(f"**Required before or after.** {r['validations']}")
        A("")
    A("**D3A and D3B stay separate.** D3A is compression, which is inherent "
      "to censoring and survives any floor value. D3B is level, which a floor "
      "correction fixes and which unties nothing. 2R.2 measured both: the tie "
      "block is the same size at every floor from 280 to 4,000 and grows as "
      "the floor falls.")
    A("")
    A("---")
    A("")

    # ================================================ 4. predictive claim
    A("## 4. The predictive claim")
    A("")
    A("The strongest wording the evidence supports, and the wording that "
      "should appear in every reader-facing document:")
    A("")
    A("> On the WestJet Calgary historical replay, the full engine showed **no "
      "detectable incremental ranking value over a demand-only baseline at "
      "effects larger than the study's resolution**. Smaller effects remain "
      "unresolved. This is a bounded negative result, not a demonstration "
      "that the engine is equivalent to ranking by modelled demand.")
    A("")
    A("It must be published with its bound attached, from Stage 2R.0:")
    A("")
    A("| bound | value |")
    A("|---|---|")
    A(f"| distinct launch events in the flagship study | "
      f"**{res['launch_events']}** (on {res['positive_rows']} positive rows; "
      "a launch inside two cutoff windows is a positive at both) |")
    A(f"| decision vintages | **{res['vintages']}** |")
    A(f"| optimistic detectability floor | **about {res['mde_events']} net "
      "launch events, spread across at least two vintages** |")
    A(f"| largest observed difference | {res['observed_events']} launch "
      "event |")
    A(f"| effects confined to one vintage | not detectable at any magnitude "
      f"the sample permits ({res['single_date_detected']} of the single-date "
      "allocations tested exclude zero) |")
    A(f"| k={', '.join(str(k) for k in res['dead_k'])} | no improvement is "
      "expressible at all, so the zero difference there is saturation |")
    A("")
    A("The floor is called optimistic deliberately: 2R.0 derives it from an "
      "oracle construction scored against an interval that omits "
      "decision-vintage uncertainty. Both push it down.")
    A("")
    A("### Is that enough for the portfolio?")
    A("")
    A("**Yes, and it is the stronger story.** The project's stated premise is "
      "validation and falsification, not predictive superiority. What it can "
      "now show is a point-in-time replay built before the results were seen, "
      "a pre-registered protocol, a measured resolution limit, a mechanical "
      "explanation for the null, four structural defects found by the "
      "project's own instruments, and a scope narrowed to what the evidence "
      "supports. A claim of predictive superiority resting on "
      f"{res['launch_events']} launch events across {res['vintages']} "
      "vintages would be the weaker artifact, and an interviewer who checked "
      "would find it.")
    A("")
    A("2R.1 adds the part a bare null cannot: **why**. Away from capacity "
      "`margin_pct` is a monotone function of captured demand times a "
      "distance-driven fare-over-cost factor, so the engine is a demand "
      "ranking tilted by share and distance rather than an independent "
      "signal. The null is explained, not merely reported.")
    A("")
    A("---")
    A("")

    # ================================================ 5. ranking exposure
    A("## 5. Is the margin ranking a valid public output?")
    A("")
    A("What a continuous public ranking would be ordering:")
    A("")
    A("| study | date | candidates | clearing the feasibility floor | with "
      "positive margin | not PASS | best margin in the top ten | worst |")
    A("|---|---|---|---|---|---|---|---|")
    for _, r in a["ranking"].iterrows():
        A(f"| {r['study_id']} | {r['cutoff']} | {r['candidates']} | "
          f"{r['feasible']} | {r['positive_margin']} | "
          f"{r['launch_or_monitor']} | {r['top10_best_margin']:,.0f}% | "
          f"{r['top10_worst_margin']:,.0f}% |")
    A("")
    rk = a["ranking"]
    neg = int((rk["top10_best_margin"] < 0).sum())
    A(f"At {neg} of {len(rk)} study-dates the published top ten would be an "
      "ordering of markets whose **best** case is a negative margin, in three "
      "cases beyond a hundred percent negative. Ordering them implies a "
      "precision and an actionability the underlying numbers do not carry, "
      "and 2R.2 shows the same ranking pulls uninformative survey-ceiling "
      "rows into its top k where the demand ranking never does.")
    A("")
    cf = a["capfeas"]
    A(f"A feasibility gate removes that second problem completely: **"
      f"{cf['capped_clearing_floor']} of {cf['capped_rows']} survey-ceiling "
      f"rows clear the floor** at any frequency, the highest reaching a load "
      f"factor of {cf['max_capped_lf']:.3f}. Under option B the tied block "
      "cannot appear in an ordered set at all, which is what makes D3A a "
      "documentation item rather than a fix.")
    A("")
    A("### Decision")
    A("")
    A("> **Option B: verdict first, ordering only within candidates that "
      "clear the feasibility floor.** Everything below the floor is presented "
      "as an unordered PASS set with the reason it failed, not as ranks 11 "
      "through 88.")
    A("")
    A("Option C is too strong: where a market does clear the floor the "
      "ordering is meaningful, and Porter has such markets. Option A is "
      "indefensible for the reason above.")
    A("")
    A("**The continuous ranking is retained as a research instrument.** "
      "Family 4 needs a total order over identical rows to compare against "
      "the demand percentile, and that comparison is the project's central "
      "result. What changes is its status: it is a comparator inside the "
      "replay, never a recommendation ordering in the product. No "
      "implementation change is made here.")
    A("")
    A("---")
    A("")

    # ================================================ 6. minimal plan
    A("## 6. Minimal remaining work plan")
    A("")
    A("Only work required to reach portfolio ready. Nothing is carried "
      "forward from the old roadmap without evidence in this document.")
    A("")
    plan = [
        ("T1", "correctness",
         "Fix D1 in isolation under a change report",
         "the corridor growth term is a raw two-year T-100 ratio with no "
         "COVID handling; demand at 2023-01 is wrong by 5.4x",
         "2R.4's before-and-after table, including the predictions it makes: "
         "WestJet rankings and verdicts unchanged, Porter verdicts move"),
        ("T2", "scope",
         "Retire the right-sizing claim across the reader-facing surfaces",
         f"{len(cl)} lines in {cl['file'].nunique()} files describe an "
         "optimisation the model does not perform",
         "the audit table in section 1 must come back empty, and the "
         "consistency tests must cover the replacement wording"),
        ("T3", "validation",
         "Extend the share validation to the connection-only stratum (W2.3)",
         "the layer that does most of the differentiating is checked in a "
         "regime the flagship study barely occupies",
         "MAE by market structure with a usable n in the zero-nonstop "
         "stratum, published in docs/validation.md"),
        ("T4", "documentation",
         "Document D3A, D3B and the resolution bound in LIMITATIONS",
         "three findings currently live only in Stage 2R documents",
         "the consistency tests, which already guard reader-facing numbers"),
        ("T5", "verification",
         "Re-run the frozen replay and the V2 comparison after T1",
         "V2 is the scoreboard and D1 is the only model change",
         "a new freeze document stating what moved and why, per V2 section 6"),
        ("T6", "audit",
         "Final audit and packaging",
         "the project's own definition of done",
         "`make all && make test` green from clean, `make reproducibility`, "
         "consistency tests, PROGRESS.md current"),
    ]
    A("| # | kind | task | why it is required | how it is verified |")
    A("|---|---|---|---|---|")
    for t in plan:
        A("| " + " | ".join(t) + " |")
    A("")
    A("**Explicitly not in the plan.** W2.1, W2.2, W2.4 and W2.5; any new "
      "carrier or study; ADS-B; new APIs or frontends; smaller gauges or "
      "sub-3x schedules; any further tuning of a metric. The D3B floor "
      "correction is out by the decision in section 3, and D3A needs no code.")
    A("")
    A("### Order and dependencies")
    A("")
    A("T1 before T5. T2, T3 and T4 are independent of both and of each other. "
      "T6 last. Only T1 changes model behaviour; T3 adds a validation output "
      "and changes no model default.")
    A("")

    # ================================================ 7. finish line
    A("## 7. Finish line")
    A("")
    A(f"**{len(plan)} material tasks remain**, of which **one** changes the "
      "model (T1), one adds a validation (T3), two are documentation and "
      "scope corrections (T2, T4), and two are verification (T5, T6).")
    A("")
    A("For comparison, the superseded plan carried five W2 ingestion and "
      "calibration programmes, four of which this document classifies NOT "
      "JUSTIFIED and the fifth of which is replaced by a validation that "
      "needs no new data.")
    A("")
    A("No new scope was created by this stage.")
    A("")

    A("## What was and was not done")
    A("")
    A("- No repair. D1, D2, D3A and D3B are exactly as V2 froze them.")
    A("- No model behaviour, assumption, threshold or scoring function "
      "changed. `SURVEY_THRESHOLD` unchanged.")
    A("- No data ingested, no `make data`, no network call.")
    A("- No W2 task started.")
    A("- V2 not modified. No reader-facing document rewritten: the "
      "terminology correction is specified here and left for T2.")
    A("")

    G.DOC.write_text("\n".join(L) + "\n")
    return "\n".join(L)


if __name__ == "__main__":
    main()
    print(f"wrote {G.DOC}")
