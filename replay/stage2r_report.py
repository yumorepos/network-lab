CAP = "unanchored_capped_at_ceiling"


def _artifacts() -> dict:
    cache = SNAP.build()
    dec = pd.read_parquet(X.REPLAY / "decision_rows.parquet")
    out = pd.read_parquet(X.REPLAY / "outcomes.parquet")
    ev = X.launch_events(out)
    lay = X.build_layers(cache)
    tr = X.layer_transitions(lay, dec, ev)
    cls = X.classify_layers(tr)
    top = X.layer_top_k_membership(lay, dec)
    ceil = X.ceiling_diagnostic(cache, dec, ev)
    floors = X.floor_sensitivity(cache)
    wide, eco = X.frequency_diagnostic(cache)
    fsum = X.frequency_summary(wide)
    reps = X.frequency_representatives(cache, wide, dec)
    vint, alt = X.d1_blast_radius(cache, dec)
    d1, d1rows = X.d1_comparison(cache, alt, dec, ev)
    d1met = X.d1_descriptive_metrics(d1rows)
    a = dict(cache=cache, dec=dec, ev=ev, lay=lay, tr=tr, cls=cls, top=top,
             ceiling=ceil, floors=floors, wide=wide, fsum=fsum, reps=reps,
             vint=vint, d1=d1, d1rows=d1rows, d1met=d1met)
    X.OUT.mkdir(parents=True, exist_ok=True)
    for name in ("tr", "cls", "top", "ceiling", "floors", "wide", "reps",
                 "vint", "d1", "d1met"):
        a[name].to_parquet(X.OUT / f"diag_{name}.parquet", index=False)
    return a


def _pct(x) -> str:
    return "n/a" if x != x else f"{x:,.1f}%"


